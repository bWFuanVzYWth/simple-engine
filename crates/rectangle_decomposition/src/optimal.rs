//! 64×64 非零标签区域的最少同标签矩形划分，允许孔洞、多个分量和 T 形接缝。
//!
//! 标签为 `u16`，零值为空；需要保留完整 `u32` 材料的应用须在上层建立标签映射。
//! [`DenseLabels64`] 提供行主序输入，[`QuadLeaf64`] 提供无重叠、按边长对齐的
//! dyadic 正方形输入。输出矩形不受输入 LOD 限制，每个非零像素恰覆盖一次。
//!
//! 算法提取连接同色凹角的水平、竖直 chord，以闭端点相交建立二分冲突图，
//! 用 HKDW 最大匹配及 Kőnig 覆盖构造最大独立集，再将选中切线扫描为矩形。
//! 不同标签的 chord 不相交，可在同一图上精确求解；不是以贪心分解代替最小数量。
//! 数字区域归约见 [Ferrari 等（1984）](https://doi.org/10.1016/0734-189X(84)90139-7)，
//! 匹配见 [Hopcroft、Karp（1973）](https://doi.org/10.1137/0202019) 及
//! [Duff、Kaya、Uçar（2011）§3.3.2](https://doi.org/10.1145/2049673.2049677)。
//! 此支持域是有限网格像素集合，不包含零宽障碍或任意实数坐标多边形。
//!
//! 固定容量内核使用区间事件、512-bit 逻辑分块、
//! 稀疏 CSR、计数散布及显式 DFS 栈。向量宽度不要求 AVX-512。少于 512 个叶子
//! 使用稀疏事件，其余栅格化到 scratch；连续输入直接扫描。推广边长的时间上界
//! 为 `O(n³)`，固定容量空间为 `O(n²)`。
//!
//! 每个 worker 独占 [`SparseOptimalScratch64`]，内部不分配、不调度；所有数组
//! 已初始化并保留到所有者销毁。x86_64 上 scratch 约 258 KiB，按引用复用，
//! 核算 worker 栈、输入、输出和并发数量；移到堆上也需考虑构造时的栈临时值。
//! [`PackedRectangles64`] 是调用方持有的 SoA 输出；借用切片保留原内核的 AoS
//! 输出路径，供已有消费者及布局基准使用。输出顺序确定；不承诺跨版本保留具体最优切法。
//!
//! # 验证规范
//!
//! 以下规范由生产同源 Verus 入口检查，覆盖稀疏／连续输入的 borrowed、packed 与 sink 六个分解入口。
//! 目标覆盖全部合法 64×64 标签图，不限于无孔洞、单分量或小尺寸输入。
//! 完整有界入口为 `scripts/verify_rectangles.ps1`，固定工具链并检查正式装配、局部性质及违规反例。
//! 普通 Cargo 不运行证明器；验证入口共享模块，验证单元数不能直接相加。
//!
//! ## 结果规范
//!
//! 记 `G = {0,...,63}²`，标签图为 `L: G -> u16`，背景为 0。
//! 矩形 `r` 表示整数闭开区域 `[x0,x1) × [y0,y1)`，记其单元集合为 `cells(r)`。
//! `Partition(L,R)` 定义为有限矩形序列 `R` 同时满足：
//!
//! - 每个 `r` 有 `0 <= x0 < x1 <= 64`、`0 <= y0 < y1 <= 64` 和非零 `value`。
//! - `p ∈ cells(r)` 蕴含 `r.value = L(p)`。
//! - 对每个 `p ∈ G`，`|{i | p ∈ cells(R[i])}| = if L(p) != 0 { 1 } else { 0 }`。
//!
//! 定义 `Opt(L) = min {|Q| | Partition(L,Q)}`；逐非零单元分解保证该最小值存在。
//! 所有成功入口应满足 `Partition(L,R) ∧ |R| = Opt(L)`；比较对象允许任意整数边界、
//! 孔洞、多个分量及 T 形接缝，不要求矩形保留输入 dyadic 分块。
//! 等价的最优性结论为 `∀Q, Partition(L,Q) ⇒ |R| <= |Q|`。
//! 推论为 `|R| <= |{p | L(p) != 0}| <= 4096`，空图当且仅当结果为空。
//!
//! ## 证明范围与优先级
//!
//! 1. **精确覆盖与输入边界**：稀疏／连续输入均构造同一 `L` 的最大非零同行／同列区间；
//!    chord 与切线不改变标签域，扫描分区既不遗漏也不重叠。非法叶子在交付输出前拒绝。
//! 2. **容量、安全与终止**：全部合法输入都成功，不能以 `CapacityOverflow`、panic 或
//!    `invariant_failed` 退出；sink 返回错误除外。全部输入路径均应有界、无越界、
//!    算术溢出或非法移位。尤其须证明无检查的固定缓冲写入不会触及 abort 路径。
//! 3. **全局最优性**：完整提取同标签凹角间的内部轴向 chord；冲突图恰表示闭端点相交，
//!    HKDW 得到最大匹配，Kőnig 对偶得到最大独立集。还须证明离散几何归约的下界，
//!    以及实际扫描分区达到该下界；只证明独立集最大不能推出输出最优。
//!    归约直接按每个顶点的同色象限计数，不假设 Euler 公式、孔数或连通性。
//! 4. **表示与复用**：同一输入的 borrowed、成功 sink 与 packed 解码得到相同序列；
//!    Kőnig 可达闭包的极值性质确定选线，实际扫描序列仅由 `L` 决定；
//!    相同 `L` 的叶子排列、合法分块和连续输入也得到相同序列。历史 scratch 内容不影响结果或错误。
//!
//! 证明应装配生产同源实现；独立 oracle、现有穷举测试及文献不是生产代码证明。
//! 特别不能将像素域到几何图的归约作为未说明的假设。
//! 32-lane `u16` SIMD 比较的位掩码由最小标准库适配绑定；
//! 调用方的切片、移位及边界 32 的拼接从实际代码证明。
//! `verify/std.rs` 集中六项可信绑定：固定 vstd 缺失的 `u64`／`u128::count_ones`，
//! `u16` 片段 fill、64×64 `u16` flatten、32-lane SIMD 比较，以及单次 Rust `FnMut` dispatch。
//! 后四者只委托标准库比较／借用／赋值或单次调用，不包含输入、搜索或分解算法。
//! 有限位和与界限另经检查，不假设算法容量或结果。
//! Rust 借用、标准库／编译器与足够的宿主栈空间属于可信边界；
//! callback 绑定不规定闭包返回值或状态；参数和实际返回事件由已验证驱动逐次记录。
//! 调用方标签映射、sink 自身及其分配行为不在内核结论中。sink 须逐次终止并正常返回，
//! panic／进程退出不属于错误返回或复用保证。性能和无堆分配约束需另行审查及实测。
//!
//! ## 证明装配
//!
//! `implementation` 入口直接装配真实 `src/lib.rs`，检查六个分解入口及其完整生产调用链。
//! 其它入口复用同源模块检查局部性质和违规反例，验证单元数不可相加。
//!
//! 输入证明覆盖单位叶子、稀疏事件和栅格扫描三条路径，含完整形状／重叠校验。
//! chord 提取恰为全部 good chord；闭端点扫线、稳定排序和 CSR 构造保持每条边恰一次。
//! 真实 HKDW 的 BFS、分层及追加 DFS、增广与终止产生最大匹配及等大覆盖，继而得到规范最大独立集。
//! 每轮匹配数严格增加；追加搜索不依赖阶段最短距离单调。
//! raw cuts 的位图与实际 `RectScan` 连接同一数学扫描序列，AoS／packed 直接消费；
//! sink 首错停止、原错误与计数由实际事件前缀刻画。稳定小 owner 不变量维持错误后的复用。
//!
//! 几何下界对任意真实 [`Rectangle`] 分区计数，同色 cut 链及冲突删除见证产生独立集；
//! 实际扫描达到同一角点下界，推出全部合法 64×64 输入的全局最优性。
//! 固定域容量和终止属于证明；渐近复杂度、无堆分配与实际性能仍由分析、审查及测量覆盖。
//! 派生 trait 的标准语义不计为分解算法证明；未纳入入口的代码不计覆盖。
//! 索引违约分支在 Verus 中将标准库 abort 映射为 panic，只证明它在索引前提下不可达；
//! 标准库 abort 的不返回行为属于最小适配边界，不假设未验证调用者满足前提。
//!
//! ```
//! use rectangle_decomposition::optimal::{DenseLabels64, PackedRectangles64, SparseOptimalScratch64};
//! let mut labels = DenseLabels64::new();
//! labels.rows_mut()[0][0] = 7;
//! let mut scratch = SparseOptimalScratch64::new();
//! let mut output = PackedRectangles64::new();
//! scratch.decompose_labels_packed(&labels, &mut output)?;
//! assert_eq!(output.labels(), &[7]);
//! # Ok::<(), rectangle_decomposition::optimal::SparseQuadError>(())
//! ```

